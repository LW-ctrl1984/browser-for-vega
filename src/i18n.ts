export const translate = (
  language: AppLanguage,
  key: TranslationKey,
  values?: Record<string, string | number>,
) => {
  let text: string = translations[language][key] || en[key];
  Object.entries(values || {}).forEach(([name, value]) => {
    text = text.replace(`{${name}}`, String(value));
  });
  return text;
};

export const fontForLanguage = (language: AppLanguage) => {
  if (language === 'zh-CN') return 'Noto Sans CJK SC';
  if (language === 'zh-TW') return 'Noto Sans CJK TC';
  if (language === 'ko') return 'Noto Sans CJK KR';
  if (language === 'ar') return 'Noto Naskh Arabic UI';
  return 'Amazon Ember';
};
